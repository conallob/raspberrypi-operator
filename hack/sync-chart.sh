#!/bin/sh
# Generate the parts of the Helm chart that must never drift from the kustomize
# install (config/): the CRDs and the manager ClusterRole. Run by `make
# chart-sync`; CI fails if the result differs from what is committed.
set -eu

chart=charts/raspberrypi-operator/templates

mkdir -p "$chart/crds"
for f in config/crd/rpi.*.yaml; do
	out="$chart/crds/$(basename "$f")"
	{
		echo '{{- if .Values.crds.install }}'
		echo '# Generated by hack/sync-chart.sh from config/crd. Do not edit.'
		# Keep the CRDs (and so every BootloaderPolicy) when the release is uninstalled.
		sed 's|^  annotations:$|  annotations:\n    helm.sh/resource-policy: keep|' "$f"
		echo '{{- end }}'
	} > "$out"
done

{
	echo '# Generated by hack/sync-chart.sh from config/rbac/role.yaml. Do not edit.'
	echo 'apiVersion: rbac.authorization.k8s.io/v1'
	echo 'kind: ClusterRole'
	echo 'metadata:'
	echo '  name: {{ include "raspberrypi-operator.managerName" . }}'
	echo '  labels: {{- include "raspberrypi-operator.labels" . | nindent 4 }}'
	awk '/^rules:/ {p=1} p' config/rbac/role.yaml
} > "$chart/rbac-manager-role.yaml"
